function makeEx(exerciseName: string, prefix: string, orderIdx: number): ExerciseItem {
  const item =
    EXERCISE_LIBRARY.find((ex) => ex.name === exerciseName) || EXERCISE_LIBRARY[0];
  return {
    ...item,
    id: `${prefix}_${orderIdx}`,
  };
}

